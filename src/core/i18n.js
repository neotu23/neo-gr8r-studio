export function t(s, p) {
  if (s === undefined || s === null || s === '') return '';
  let out = lang === 'zh' ? (ZH[s] ?? s) : s;
  if (p) out = out.replace(/\{(\w+)\}/g, (m, k) => (p[k] === undefined ? m : p[k]));
  return out;
}

/* Plural-aware: English picks `one` for n === 1, Chinese always uses `other`. */
export function tn(n, one, other) {
  const src = lang === 'zh' ? other : n === 1 ? one : other;
  return src.replace(/\{n\}/g, n);
}

